"""
Trains and evaluates PHC Triage following the Simulator Specification
(section 11) and writes every number to reports/. ALL RESULTS ARE ON
SYNTHETIC DATA.

  python -m ml.train                 # everything (~15 minutes)
  python -m ml.train --quick         # baseline only, no sweep / feedback loop

Steps
  1. Baseline world: train (months 1-30, held-out LGAs excluded), calibrate
     (31-39), test (40-48) on all LGAs and on held-out LGAs alone.
  2. Cross-world: the baseline model on every stress scenario's test months.
  3. c sweep: train and test on each c world, to find how strong the link
     between trouble and reporting must be for the tool to beat the rules.
  4. Feedback loop (spec 10): with and without random audit, and officer
     accuracy 0.7 / 0.8 / 0.9 / 1.0.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import joblib
import pandas as pd

from . import data, evaluate, features, feedback_loop, models

ROOT = Path(__file__).resolve().parents[1]
MODELS = ROOT / "models"
REPORTS = ROOT / "reports"
SCENARIOS = ["weak_link", "strong_link", "high_noise", "many_chronic", "benign_silence", "fast_attrition",
             "insecure", "sparse_stock"]
C_SWEEP = ["c0", "c0.25", "c0.5", "c1", "c2", "c3"]


def log(msg, t0):
    print(f"[{time.time() - t0:6.0f}s] {msg}", flush=True)


def panel_for(world: str) -> tuple[pd.DataFrame, data.Visible]:
    vis = data.load_visible(world)
    return features.attach_labels(features.build_panel(vis), data.load_truth(world), vis.periods), vis


def headline(rep: dict) -> dict:
    c = rep["comparison"]
    row = {"base_rate": c["model"]["per_lga_k5"]["base_rate"], "auc": rep["calibration"]["auc"]}
    for name, key in (("model", "model"), ("silent_2m", "baseline_a_silent_2_months"),
                      ("low_rate", "baseline_b_low_reporting_rate"), ("random", "random")):
        row[f"{name}_p@5_lga"] = c[key]["per_lga_k5"]["precision"]
        row[f"{name}_p@20_state"] = c[key]["per_state_k20"]["precision"]
    row["beats_both_baselines"] = row["model_p@5_lga"] > max(row["silent_2m_p@5_lga"], row["low_rate_p@5_lga"])
    return row


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    args = ap.parse_args()
    t0 = time.time()
    MODELS.mkdir(exist_ok=True)
    REPORTS.mkdir(exist_ok=True)
    cfg = json.loads((data.DATA / "baseline" / "run_metadata.json").read_text())["parameters"]

    # 1. Baseline -----------------------------------------------------------
    panel, vis = panel_for("baseline")
    held = models.heldout_lgas(panel)
    bundle = models.fit_all(panel, held)
    joblib.dump(bundle, MODELS / "bundle.joblib")
    log("baseline trained", t0)
    scored = models.score(bundle, panel)
    test = scored[scored.t.isin(models.TEST_MONTHS)]
    report = {
        "SYNTHETIC": True,
        "note": "All numbers are from synthetic data generated by the PHC Triage simulator (real GRID3 locations, "
                "simulated reporting and outcomes). They show the method works under the simulator's assumptions; "
                "they are not evidence about real facilities.",
        "label": "serious trouble in the next 1-2 months (team definition; see simulator/labels.py)",
        "splits": {"train_months": [1, 30 - models.HORIZON], "validation_months": [31, 39 - models.HORIZON],
                   "test_months": [40, 48 - models.HORIZON], "embargo_months": models.HORIZON,
                   "heldout_lgas": sorted(held)},
        "baseline_world": {"all_lgas": evaluate.full_report(test),
                           "heldout_lgas_only": evaluate.full_report(test[test.lga.isin(held)])},
    }
    log("baseline evaluated", t0)

    if not args.quick:
        # 2. Cross-world ------------------------------------------------------
        cross = {}
        for s in SCENARIOS:
            p, _ = panel_for(s)
            sc = models.score(bundle, p)
            cross[s] = headline(evaluate.full_report(sc[sc.t.isin(models.TEST_MONTHS)]))
            log(f"cross-world {s}", t0)
        report["cross_world"] = cross

        # 3. c sweep ----------------------------------------------------------
        sweep = {}
        for c in C_SWEEP:
            p, _ = panel_for(f"c_sweep/{c}")
            h = models.heldout_lgas(p)
            b = models.fit_all(p, h)
            sc = models.score(b, p)
            sweep[c] = headline(evaluate.full_report(sc[sc.t.isin(models.TEST_MONTHS)]))
            log(f"c sweep {c}", t0)
        report["c_sweep"] = sweep

        # 4. Feedback loop ----------------------------------------------------
        months = range(30, 48 - models.HORIZON)
        fb = {}
        recs, rounds = feedback_loop.run(panel, bundle, cfg, months, audit=True, seed=1)
        recs.drop(columns=["truth_serious_now"]).to_csv(data.DATA / "baseline" / "feedback.csv", index=False)
        rounds.to_csv(REPORTS / "feedback_rounds.csv", index=False)
        fb["with_audit"] = {**feedback_loop.summarise(rounds), "rounds_table": rounds.to_dict(orient="records")}
        log("feedback loop (with audit)", t0)
        _, r2 = feedback_loop.run(panel, bundle, cfg, months, audit=False, seed=1)
        fb["without_audit"] = feedback_loop.summarise(r2)
        _, r0 = feedback_loop.run(panel, bundle, cfg, months, audit=True, seed=1, retrain=False)
        fb["no_retraining_control"] = feedback_loop.summarise(r0)
        for a in (0.7, 0.8, 0.9, 1.0):
            _, ra = feedback_loop.run(panel, bundle, cfg, months, audit=True, accuracy_override=a, seed=1)
            fb[f"officer_accuracy_{a}"] = feedback_loop.summarise(ra)
            log(f"feedback loop accuracy {a}", t0)
        report["feedback_loop"] = fb

    (REPORTS / "validation.json").write_text(json.dumps(report, indent=2, default=str))
    (REPORTS / "validation.md").write_text(to_markdown(report))
    log(f"wrote {REPORTS / 'validation.json'} and validation.md", t0)


def _pct(x):
    return "—" if x is None else f"{x:.0%}"


def to_markdown(r: dict) -> str:
    b = r["baseline_world"]["all_lgas"]
    hb = r["baseline_world"]["heldout_lgas_only"]
    c = b["comparison"]
    lines = [
        "# PHC Triage — validation results (SYNTHETIC DATA)", "",
        f"> {r['note']}", "",
        f"**Target:** {r['label']}. **Test:** months 40–46 of the baseline world, "
        f"{b['facility_months']:,} facility-months. Base rate {_pct(c['model']['per_lga_k5']['base_rate'])}.", "",
        "## Model vs baselines (baseline world, all LGAs)", "",
        "| Method | Precision, top 5 per LGA | Recall, top 5 per LGA | Precision, top 20 per state | Early warning of new trouble |",
        "|---|---|---|---|---|",
    ]
    names = {"model": "**Model**", "baseline_a_silent_2_months": "Baseline (a): silent 2+ months",
             "baseline_b_low_reporting_rate": "Baseline (b): low reporting rate", "random": "Random"}
    for k, label in names.items():
        v = c[k]
        lines.append(f"| {label} | {_pct(v['per_lga_k5']['precision'])} | {_pct(v['per_lga_k5']['recall'])} | "
                     f"{_pct(v['per_state_k20']['precision'])} | {_pct(v['detection']['early_rate'])} |")
    hc = hb["comparison"]
    lines += ["", f"**Held-out LGAs only** (never seen in training): model {_pct(hc['model']['per_lga_k5']['precision'])} "
              f"vs silent-2-months {_pct(hc['baseline_a_silent_2_months']['per_lga_k5']['precision'])} "
              f"vs low-rate {_pct(hc['baseline_b_low_reporting_rate']['per_lga_k5']['precision'])} (precision, top 5 per LGA).",
              "", f"**Calibration:** Brier {b['calibration']['brier']}, AUC {b['calibration']['auc']}.", "",
              "## Fairness (top 5 per LGA)", "", "| Group | Base rate | Flag rate | Precision | Recall |", "|---|---|---|---|---|"]
    for g, v in b["fairness"].items():
        lines.append(f"| {g} | {_pct(v['base_rate'])} | {_pct(v['flag_rate'])} | {_pct(v['precision'])} | {_pct(v['recall'])} |")
    s = b["silence_type"]
    lines += ["", "## Silence type (model 2)", "",
              f"Accuracy {_pct(s['accuracy'])} (always guessing the commonest cause: {_pct(s['majority_class_accuracy'])}), "
              f"macro F1 {s['macro_f1']}. Recall by cause: "
              + ", ".join(f"{k} {_pct(v)}" for k, v in s["recall_by_cause"].items())
              + f". Insecurity modifier agrees with truth {_pct(s['insecure_modifier_agreement'])} of the time.", "",
              "## Failure types", "", "| Type | Base rate | AUC |", "|---|---|---|"]
    for k, v in b["failure_types"].items():
        lines.append(f"| {k} | {_pct(v['base_rate'])} | {v['auc']} |")
    if "c_sweep" in r:
        lines += ["", "## How strong must the reporting link be? (c sweep, train and test per world)", "",
                  "| c | AUC | Model | Silent 2m | Low rate | Beats both? |", "|---|---|---|---|---|---|"]
        for k, v in r["c_sweep"].items():
            lines.append(f"| {k[1:]} | {v['auc']} | {_pct(v['model_p@5_lga'])} | {_pct(v['silent_2m_p@5_lga'])} | "
                         f"{_pct(v['low_rate_p@5_lga'])} | {'yes' if v['beats_both_baselines'] else 'no'} |")
        lines += ["", "## Stress test: baseline model on other worlds (precision, top 5 per LGA)", "",
                  "| World | Base rate | Model | Silent 2m | Low rate | Random |", "|---|---|---|---|---|---|"]
        for k, v in r["cross_world"].items():
            lines.append(f"| {k} | {_pct(v['base_rate'])} | {_pct(v['model_p@5_lga'])} | {_pct(v['silent_2m_p@5_lga'])} | "
                         f"{_pct(v['low_rate_p@5_lga'])} | {_pct(v['random_p@5_lga'])} |")
    if "feedback_loop" in r:
        f = r["feedback_loop"]
        lines += ["", "## Simulated feedback loop (mechanism only, not real officer behaviour)", "",
                  "| Run | Confirmed share, first 3 rounds | Last 3 rounds | True precision first 3 | Last 3 | Couldn't verify |",
                  "|---|---|---|---|---|---|"]
        for k, v in f.items():
            lines.append(f"| {k.replace('_', ' ')} | {_pct(v['confirmed_share_first_3'])} | {_pct(v['confirmed_share_last_3'])} | "
                         f"{_pct(v['true_precision_first_3'])} | {_pct(v['true_precision_last_3'])} | {_pct(v['could_not_verify_share'])} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    main()
